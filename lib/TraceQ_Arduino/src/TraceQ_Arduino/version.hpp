#pragma once
/**
 * \brief TraceQ Arduino 펌웨어 버전.
 *
 * 2.0.0 — 1.0(=1.4.1) 코드베이스를 분석해 RFID 안전성/속도를 재설계 (미완).
 * 2.1.0 — 1.4.1 전 기능 완성판: legacy 서버 프로토콜 전체 이식, raw 시리얼
 *         수신 복원(현장 PC 호환), 소독기 RTC 자동 복구 원복, 태그 발급
 *         키 전환(공장↔TraceQ) 완성, 1.4.1 승계 버그(스택 오버런 6곳,
 *         소독기 매니저 인스턴스 불일치 등) 수정. nested auth 수정 실기 합격.
 * 2.2.0 — 서버 Latest 갈래 삭제(사용자 확정): 서버는 레거시 블록 덤프
 *         단일 경로. Version(Latest/Old) 메뉴·EEPROM 플래그(주소 0)·latest
 *         스텁 제거, 부팅 PSOk 는 서버 타입이면 항상 송신.
 * 2.2.1 — LCD 날짜/시간 저장 시 범위 검증 (월 1~12·일 1~31·시 0~23·분초
 *         0~59) — 1.0부터 있던 월 99 등 쓰레기 값 RTC 저장 구멍 보강.
 *         잘못된 값은 저장하지 않고 Invalid Date/Time 경고 후 폐기.
 * 2.2.2 — RTC 배터리 방전 시 2026-01-01 00:00:00 고정 (1.0은 컴파일 시각).
 *         고정 날짜 = 배터리 방전 식별 마커 + 소독기 RTC 자동 복구 확실 발동.
 * 2.2.3 — 새 빌드 업로드 시 EEPROM 완전 초기화(설정값 포함, 사용자 확정).
 *         빌드 도장(컴파일 시각 해시, 주소 4088) 불일치 = 새 펌웨어 첫 부팅
 *         → 전체 소거+기본값. 1.0의 DATA_NEEDS_INIT(4095) 방식은 구버전이
 *         깔려 있던 기기에서 초기화를 건너뛰어 이중 업로드가 필요했다.
 * 2.2.4 — 초기화 시 액교환일(ClearDateTime) 기본값 = 현재로부터 1개월 전
 *         (사용자 확정). 비어 있으면 소독 기록마다 현재시각이 교환일로
 *         찍혀 통계 주기가 흩어지던 것 방지 — 클리어 태그 등록 전까지
 *         안정된 기준일 제공.
 * 2.2.9 — 실패를 조용히 넘기지 않는다 + 소리 규칙 통일 + 업로드 시 설정 유지/초기화 선택 (사장님 09-23).
 *         [알림] 세척·소독 종료·소독 이동·게이트웨이(본 경로/폴백)·서버(덤프 뒤 소거)·담당자 등록·
 *           태그 읽기까지, 기록이 안 됐는데 완료음이 나던 자리를 전부 막았다. 실패하면 LCD 에
 *           Write/Read Error 를 띄우고 실패음을 내며 알람·커밋·성공음이 없다.
 *         [소리] 부저는 한 소리뿐이라 리듬으로 가른다 — 정상=짧게1 · 환자정보없음(기록은 됨)=길게2 ·
 *           실패(다시 대면 됨)=짧게4 · 거부(여기선 안 되는 태그)=삐삐+긴삐. 기기·단계와 무관하게 같은 뜻.
 *         [서버] 덤프 뒤 초기화 순서 재정의: 환자정보표시 내림 → 게이트웨이·검사항목 소거 → 완료 커밋 →
 *           환자 블록 소거. 중간에 멈춰도 "환자정보 있음인데 블록은 빈" 태그가 남지 않고, 2차 덤프가
 *           빈 환자정보로 PC 기록을 덮어쓰지 않는다. 성공 결과는 1.4.1 과 바이트 동일.
 *         [업로드] 쓰던 기기면 첫 부팅에 "Keep settings?" 를 묻는다(SELECT=유지 / RIGHT 0.2초=완전 초기화 /
 *           10초 무응답=유지). 공장 기기는 묻지 않고 초기화. 전원 켤 때 RIGHT 을 누르고 있으면 같은 판에서도
 *           다시 고를 수 있다. 유지하면 1.4.1 과 EEPROM 주소가 같아 기기번호·세척시간·담당자·소독 횟수·
 *           액교환일이 그대로 남는다(177번지의 알 수 없는 값만 정리).
 * 2.2.8 — 3차 전체 로직 감사 반영(docs/AUDIT_2026-09-23.md) — 2.2.7 이 넣은 결함 3 포함. 상태를 늘리지 않고 고쳤다:
 *         · 액교환일 미룸의 "시계 맞춰짐" 판정을 RAM 플래그 → 시계 값(출시일 이전 = 미동기)으로.
 *           RAM 플래그는 PC 접속(DTR 리셋)·재시작·시간만 맞춤에 지워져 표지 시각이 교환일로 박혔다.
 *         · 더블터치 판정을 RAM 의 마지막 시작 → 태그에 적힌 시작 시각으로(Write Error 뒤 1초 종료·재부팅 사이 대응).
 *         · 더블터치 재시작은 커밋된 시작을 지우지 않음(중간 실패 시 시작 0 태그).
 *         · 발급 대기는 WUPA 로 정지된 태그도 깨움 · raw 머리글자(G/C/M/S/Z)면 JSON 판정 생략 · str_atoi 오버플로 검사 정정.
 *         · 시뮬레이터 하네스: 진짜 리셋(hard_reset)·WUPA·readErrSkip, 시험 115.
 * 2.2.7 — 2차 전체 로직 감사 반영(docs/AUDIT_2026-09-22.md). 핵심:
 *         · 소독기 RTC 복구에서 세척 종료 기록이 비면 "세척 시작+설정 세척시간+1분"
 *           (종전엔 0 에 +1분 해 unixtime 이 돌아 RTC 가 2043년에 굳었다).
 *         · 액교환일: 시계가 방전 표지(2026-01-01)면 미뤘다가 시계가 맞춰질 때 기록.
 *         · 세척·소독 시작 기록 실패를 성공으로 알리지 않음(Write Error).
 *         · 더블터치 2초 판정을 "방금 시작한 그 태그"로(guest 포함), 세척기에도 적용.
 *         · Poll 3회 무응답만 이탈(인증 실패·HaltA 유실 뒤 재처리 방지), 발급은 ForgetTag.
 *         · 서버 덤프에 읽기 실패가 있었으면 태그를 지우지 않음(재스캔 복구).
 *         · 메뉴 숫자 전 자릿수 저장·날짜 월말 검증·JSON 값 클램프 뒤 좁히기·메뉴 재귀 제거.
 *         · 게이트웨이 수신 대기 1초(올눈 250ms 조각 전송), G3·G4 필드 16바이트 전부 저장.
 * 2.2.6 — 게이트웨이 본체번호를 PC(SeePro)가 G1 으로 내려준 값으로 기록.
 *         G1 이 0(=`0000`)이거나 미수신이면 기기 자체 번호를 쓴다(사용자 확정).
 *         1.0 은 G1 구간을 읽지 않고 항상 기기 번호를 썼다. 홈 화면 우하단은
 *         **실제 기록될 번호**를 표시한다.
 * 2.2.5 — 전체 로직 감사 반영. 핵심:
 *         · 세션 도중 StopCrypto1 금지 규칙을 Read 실패·태그 발급 경로까지
 *           확대(암호화 상태를 mCryptoOn 으로 분리 추적). 서버 덤프가 1회
 *           읽기 실패 후 전량 0 으로 나가던 것, 태그 발급(type 0/2)이 항상
 *           실패하던 것 수정. Read 는 nested 재인증 1회 재시도.
 *         · 기록 커밋 순서 정정(소독 Process·게이트웨이 Status 를 마지막에)
 *           → 중간 실패 시 "했다고 표시되지만 기록은 빈" 태그가 남지 않음.
 *         · 소독 횟수 오계상 2건: 더블터치 재시작 중복 증가, guest 슬롯 잔존.
 *         · 메뉴 숫자 버퍼 오버런(값 100 이상), abort() 영구정지 → 소프트리셋,
 *           기기 타입 EEPROM 손상 시 기본값 폴백, 동시소독 지연 상한 클램프.
 *         · 응답성: Home 화면 변경분만 LCD 갱신, 시리얼 수신 타임아웃 1s→150ms
 *           (두 G 패킷 병합으로 옛 환자정보가 채택되던 위험도 함께 축소).
 *         · 진단: 태그 읽기 실패 사유 표시, legacy 덤프 읽기 실패 경고.
 *         · 도장 기준을 빌드 시각 → **버전 문자열**로 변경(결정적 규칙:
 *           버전이 오른 펌웨어를 올리면 완전 초기화, 같은 버전은 설정 유지).
 */
